from django.contrib.auth.models import AbstractUser
from django.db import models

from apps.core.images import shrink_image_field


class User(AbstractUser):
    class Role(models.TextChoices):
        OWNER = "owner", "Batch owner"
        MEMBER = "member", "Batch member"
        COLLECTOR = "collector", "Collector / buyer"

    role = models.CharField(max_length=16, choices=Role.choices, default=Role.COLLECTOR)
    batch = models.ForeignKey(
        "batches.Batch", null=True, blank=True, on_delete=models.CASCADE, related_name="members"
    )
    display_name = models.CharField(max_length=120, blank=True)
    bio = models.TextField(blank=True)
    phone = models.CharField(max_length=20, blank=True)
    avatar = models.ImageField(upload_to="avatars/", blank=True)
    # Set for accounts whose password was generated by the batch owner.
    must_change_password = models.BooleanField(default=False)

    @property
    def name(self):
        return self.display_name or self.get_full_name() or self.username

    @property
    def is_student(self):
        return self.role in (self.Role.OWNER, self.Role.MEMBER) and self.batch_id is not None

    def save(self, *args, **kwargs):
        shrink_image_field(self.avatar, max_dim=512)
        super().save(*args, **kwargs)

    def __str__(self):
        return self.username
